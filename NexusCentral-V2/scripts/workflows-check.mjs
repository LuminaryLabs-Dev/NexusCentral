import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync, readFileSync, symlinkSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { NexusNode } from '../services/nexus-node/src/nexus-node.mjs';
import { commandEnvelope } from '../packages/contracts/index.mjs';
import { operationsTemplate, validateWorkflow } from '../packages/workflows/catalog.mjs';
import { WorkflowSandbox } from '../adapters/workflow-sandbox/index.mjs';
process.env.NODE_ENV = 'test';
const root = mkdtempSync(join(tmpdir(), 'nexus-workflows-'));
const admin = { actorId: 'operator', scopes: ['admin'] }, reader = { actorId:'viewer', scopes:['view'] };
let node = new NexusNode({ databasePath: join(root,'state.sqlite') });
const command = (name,payload={},context=admin,options={})=>node.execute(commandEnvelope(name,payload,options),context);
const wait = async (id, status) => { for(let i=0;i<300;i++){const run=node.workflowCoordinator.get(id);if(run.status===status)return run;if(run.status==='failed'&&status!=='failed')throw new Error(JSON.stringify(run));await new Promise(r=>setTimeout(r,20));}throw new Error(`Timed out waiting for ${status}`); };
try {
  const def = operationsTemplate('operations-test');
  assert.deepEqual(validateWorkflow(def,{runnable:true}),[]);
  assert(validateWorkflow({...def,edges:[...def.edges,{from:'review',to:'tasks'}]}).length);
  assert(validateWorkflow({...def,blocks:[...def.blocks,def.blocks[0]]}).length);
  assert(validateWorkflow({...def,blocks:def.blocks.map(b=>b.id==='report'?{...b,version:'99'}:b)}).length);
  await assert.rejects(command('workflows.save',{definition:def},reader),/Scope/);
  await command('workflows.save',{definition:def});
  await assert.rejects(command('workflows.save',{definition:def,expectedRevision:0}),/changed elsewhere/);
  await assert.rejects(command('apps.configure',{id:'operations',enabled:false}),/saved workflow/);
  const started = await command('workflows.start',{id:def.id},admin,{idempotencyKey:'first-run'});
  assert.equal((await command('workflows.start',{id:def.id},admin,{idempotencyKey:'first-run'})).id,started.id);
  await assert.rejects(command('workflows.start',{id:def.id}),/active run/);
  let reviewed = await wait(started.id,'needs-review');
  assert.match(reviewed.steps.report.output,/2 tasks included/);
  assert(!reviewed.steps.report.output.includes('Record the kickoff'));
  assert.equal(node.engine.n.centralJobs.getSnapshot().jobs.find(j=>j.id===started.id).status,'approval_required');
  await assert.rejects(command('workflows.approve',{id:started.id,blockId:'review'},reader),/Scope/);
  await node.close(); node = new NexusNode({databasePath:join(root,'state.sqlite')});
  assert.equal(node.workflowCoordinator.get(started.id).status,'needs-review');
  await command('workflows.approve',{id:started.id,blockId:'review'});
  await wait(started.id,'completed');
  const completed = node.workflowCoordinator.get(started.id);
  assert.equal(completed.steps.report.attempts,1);
  const artifact = await command('artifacts.read',{id:completed.steps.report.artifact.id});
  assert.match(artifact.content,/Operations report/);
  const next = await command('workflows.start',{id:def.id});
  assert.notEqual(started.id,next.id);
  await command('workflows.pause',{id:next.id});
  assert.equal(node.workflowCoordinator.get(next.id).status,'paused');
  for(let i=0;i<100&&node.workflowCoordinator.active.has(next.id);i++)await new Promise(r=>setTimeout(r,10));
  await command('workflows.resume',{id:next.id});
  await wait(next.id,'needs-review');
  await command('workflows.cancel',{id:next.id});
  assert.equal(node.workflowCoordinator.get(next.id).status,'canceled');
  const conditional = operationsTemplate('conditional');
  conditional.edges[0].when='empty';
  await command('workflows.save',{definition:conditional});
  const skipped=await command('workflows.start',{id:'conditional'});
  const skipResult=await wait(skipped.id,'completed');
  assert.equal(skipResult.steps.select.status,'skipped');assert.equal(skipResult.steps.review.status,'skipped');
  const parallel = {id:'parallel',name:'Two briefs',blocks:['first','second'].map((id,i)=>({id,action:'brief',version:'1.0.0',x:i*280,y:50,config:{title:id,text:'A bounded brief'}})),edges:[]};
  await command('workflows.save',{definition:parallel});
  const both=await command('workflows.start',{id:'parallel'});await wait(both.id,'completed');
  assert.equal(node.workflowCoordinator.get(both.id).steps.second.status,'completed');
  // Inject a worker failure to exercise recovery without external side effects.
  const execute=node.workflowCoordinator.sandbox.execute.bind(node.workflowCoordinator.sandbox);
  node.workflowCoordinator.sandbox.execute=async()=>{throw new Error('Injected worker interruption');};
  const failed=await command('workflows.start',{id:'parallel'});await wait(failed.id,'failed');
  for(let i=0;i<100&&node.workflowCoordinator.active.has(failed.id);i++)await new Promise(r=>setTimeout(r,10));
  node.workflowCoordinator.sandbox.execute=execute;
  await command('workflows.resume',{id:failed.id});await wait(failed.id,'completed');
  assert.equal(node.workflowCoordinator.get(failed.id).steps.first.attempts,2);
  // Same flags and kernel policy as real workers; deny host files, cross-run files, processes, sockets.
  const inside=join(root,'inside');mkdirSync(inside);
  const outside=join(root,'outside.txt');writeFileSync(outside,'not available to the worker');
  const probe=join(root,'probe.mjs');
  writeFileSync(probe,`import fs from 'node:fs';import net from 'node:net';import cp from 'node:child_process';\nlet denied=0;for(const fn of [()=>fs.readFileSync(${JSON.stringify(outside)}),()=>fs.writeFileSync(${JSON.stringify(outside)},'overwrite'),()=>cp.spawnSync('/bin/sh',['-c','true'])]){try{fn()}catch(e){if(e.code==='ERR_ACCESS_DENIED')denied++;}}\nconst server=net.createServer();server.on('error',()=>{if(denied!==3)process.exit(2);console.log('4 boundaries denied');});server.listen(0,'127.0.0.1',()=>process.exit(3));`);
  const result=spawnSync('python3',[resolve('adapters/workflow-sandbox/lockdown.py'),process.execPath,'--permission',`--allow-fs-read=${inside}`,`--allow-fs-read=${probe}`,`--allow-fs-write=${inside}`,probe],{encoding:'utf8',timeout:5000});
  assert.equal(result.status,0,result.stderr);assert.match(result.stdout,/4 boundaries denied/);assert.equal(readFileSync(outside,'utf8'),'not available to the worker');
  const sandbox = new WorkflowSandbox(join(root,'sandbox'));mkdirSync(join(root,'elsewhere'));symlinkSync(join(root,'elsewhere'),join(root,'sandbox','linked'));
  await assert.rejects(sandbox.execute({runId:'linked',blockId:'x',attempt:1,action:'brief',config:{},inputs:[]}),/links/);
  await command('workflows.clean',{id:started.id});
  assert(node.workflowCoordinator.get(started.id).sandboxClearedAt);
  assert.match((await command('artifacts.read',{id:completed.steps.report.artifact.id})).content,/Operations report/);
  assert(node.engine.n.centralAudit.getSnapshot().entries.some(e=>e.command==='workflow.tool.input.import'));
  assert(node.engine.n.centralAudit.getSnapshot().entries.some(e=>e.command==='workflow.tool.artifact.write'));
  console.log('PASS: workflow graph validation, revisions, permissions, app dependencies, isolated real execution, idempotency, review, artifacts, restart persistence, pause/resume, cancellation, conditions, parallel steps, retry, and four sandbox boundary probes.');
} finally { await node.close(); rmSync(root,{recursive:true,force:true}); }
